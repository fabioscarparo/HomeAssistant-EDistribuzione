"""Authentication client for E-Distribuzione.

The portal answers on two hostnames of the same Salesforce org: the custom one
(private.e-distribuzione.it) is behind Imperva and blocks non-browser clients,
so when it returns the anti-bot page login and token refresh fall back to the
canonical domain (edistribuzione.my.site.com) - same login, same community,
without the anti-bot check. The primary stays the custom domain, so the client
returns to it by itself once the block is lifted. Details in const.py.

Standard OAuth2 Authorization Code + PKCE login, but the hard part is in the
middle: the credentials are submitted via an Aura action (Salesforce
Lightning), and the OTP goes through a classic Visualforce "Login Flow" page
(ViewState/RichFaces). These are UI implementation details, not a stable public
API: this module scrapes HTML/JSON with regexes, and WILL BREAK if Enel changes
the Experience Cloud template or the RichFaces version. The most fragile parts
are the static scraping functions at the bottom of the file - the first place to
check if login starts failing.

Once a refresh_token is obtained, this fragility is no longer needed:
AuthClient.async_refresh_access_token() talks only to the standard OAuth2
endpoint.

async_begin_login runs in sequence:
    1. _carica_pagina_login       GET /oauth2/authorize (PKCE) -> login page
    2. _invia_credenziali         POST Aura loginUser -> frontdoor.jsp URL
    3. _segui_a_pagina_otp        GET frontdoor -> JS bridge -> OTP page
    4. _async_avvia_invio_otp     empty submit: actually triggers the OTP send

async_submit_otp then runs:
    5. _sottometti_codice_otp          POST the form with the OTP -> meta Location
    6. _scarica_pagina_dopo_otp        follow that redirect
    7. _estrai_codice_autorizzazione   find code/state (handling the OAuth
                                        consent on the very first authorization)
    8. _async_exchange_code            POST /oauth2/token
"""
