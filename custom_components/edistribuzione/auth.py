# Fallback field names of the login flow RichFaces form, used only if
# _analizza_pagina_otp cannot discover them dynamically from the real page (the
# "thePage:j_id2:..." prefixes are generated by Salesforce and can change
# between deploys).
_CAMPO_OTP_INPUT_DEFAULT = "thePage:j_id2:i:f:pb:d:element___input____OTP_Input"
_CAMPO_RICHIEDI_NUOVO_OTP_DEFAULT = "thePage:j_id2:i:f:pb:d:element___hidden____Richiedi_nuovo_OTP"
_CAMPO_NEXT_AJAX_DEFAULT = "thePage:j_id2:i:f:pb:pbb:nextAjax"

# Fragments with which the portal signals that the account has too many sessions
# open at once ("Hai superato il numero di sessioni simultanee consentite"). It
# must be told apart from wrong credentials and from a markup change: in this
# state the login does not proceed and the OTP is not even sent, so the user
# would be left waiting for a code that never arrives.
_MARCATORI_TROPPE_SESSIONI = (
    "sessioni simultanee",
    "sessioni contemporanee",
    "numero di sessioni",
    "sessioni consentite",
)

# Pages of Imperva's (Incapsula) anti-bot protection, which answers in place of
# the login and token endpoints when it classifies the traffic as automated: the
# "Pardon Our Interruption" JavaScript check (HTTP 200) and the "Incapsula
# incident ID" block. Only markers of these two pages: the _Incapsula_Resource
# script can also appear on normal pages of a protected site.
_MARCATORI_ANTIBOT = (
    "pardon our interruption",
    "incapsula incident id",
)

# Text with which the response to the first form submit confirms it has sent the
# code (e.g. "Abbiamo inviato un codice a 5 cifre al tuo indirizzo email").
# Several variants because the channel (email/SMS) and the wording change from
# account to account: a missing confirmation is NOT treated as a fatal error (it
# would break otherwise valid logins with a different wording), only reported.
_MARCATORI_OTP_INVIATO = (
    "abbiamo inviato",
    "inviato un codice",
    "codice a 5 cifre",
    "codice è stato inviato",
    "nuovo codice",
)

# Labels of the button that APPROVES on the OAuth consent screen. On the real
# page the two buttons share the SAME name="save" and differ only by value:
# "Consenti" approves, " Nega " (with the spaces) rejects - the wrong button
# means denying the integration's authorization, so the value is compared in
# full, not searched as a substring.
_ETICHETTE_CONSENSO = ("consenti", "allow", "approve", "autorizza", "accetta")


def _contiene(testo: str, marcatori: tuple[str, ...]) -> bool:
    minuscolo = testo.lower()
    return any(marcatore in minuscolo for marcatore in marcatori)


def _scrivi_pagina_debug(html: str, nome_file: str) -> None:
    try:
        percorso = Path(nome_file)
        percorso.write_text(html, encoding="utf-8")
    except OSError as exc:
        _LOGGER.debug("Impossibile salvare %s su disco: %s", nome_file, exc)
        return
    _LOGGER.error("Pagina completa salvata in %s", percorso.resolve())


def _salva_pagina_debug(html: str, nome_file: str) -> None:
    """Write the page to disk (best-effort) and log its path, so it can be
    requested in a bug report without having to capture a HAR.

    The write is delegated to an executor when we are inside Home Assistant's
    event loop, which flags synchronous I/O as a "blocking call". Outside an
    event loop (tests, scripts/verify_login.py) it writes directly.
    """
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        _scrivi_pagina_debug(html, nome_file)
        return
    # Deliberately not awaited: it is a best-effort diagnostic dump, it must not
    # slow down or fail the login if the disk is slow or full.
    loop.run_in_executor(None, _scrivi_pagina_debug, html, nome_file)


def _log_parsing_failure_context(html: str, campo_cercato: str) -> None:
    """Log the page title + a preview when an expected field is not found - tells
    "wrong regex" (the field is there but in a different form) from "page
    completely different from the expected one" without having to ask for another
    capture. Also saves the whole page to disk."""
    title_match = re.search(r"<title>(.*?)</title>", html, re.IGNORECASE | re.DOTALL)
    title = title_match.group(1).strip() if title_match else "(nessun <title> trovato)"
    _LOGGER.error(
        "Campo '%s' non trovato. Titolo pagina: %r. Lunghezza: %d caratteri. "
        "Primi 300 caratteri: %r",
        campo_cercato,
        title,
        len(html),
        html[:300],
    )
    _salva_pagina_debug(html, "otp_page_debug.html")


class AuthError(Exception):
    """Generic authentication error."""


class InvalidCredentials(AuthError):
    """Wrong email or password."""


class InvalidOtp(AuthError):
    """Wrong or expired OTP code."""


class TroppeSessioni(AuthError):
    """The account already has too many open sessions: the portal refuses the
    login before sending any OTP.

    It is not a credentials problem nor a markup change: until the other sessions
    are closed or expire (official app, website, previous attempts of this same
    integration) there is nothing to re-enter in the form, a session must be
    freed and the login retried.
    """


class AccessoBloccato(AuthError):
    """E-Distribuzione answered with Imperva's anti-bot page instead of the
    expected one: automated access is blocked server-side.

    It is not a credentials problem nor a markup change, and there is nothing to
    fix here: it must be reported clearly and retried later, without insisting.
    """


def _verifica_non_bloccato(testo: str) -> None:
    """Raise AccessoBloccato if the response is the anti-bot page."""
    if _contiene(testo, _MARCATORI_ANTIBOT):
        raise AccessoBloccato("E-Distribuzione ha risposto con la pagina antibot (Imperva)")


async def _leggi_testo(resp: aiohttp.ClientResponse) -> str:
    """Response body, after ruling out the anti-bot page."""
    testo = await resp.text()
    _verifica_non_bloccato(testo)
    return testo


class ParsingError(AuthError):
    """The scraped page did not contain what was expected.

    Most likely cause: Enel changed something in their Salesforce site and the
    regexes below need updating. Capture a fresh HAR and compare.
    """


def _identita(url: str) -> str:
    return url


async def _get_following_redirects(
    session: aiohttp.ClientSession,
    url: str,
    *,
    params: dict | None = None,
    headers: dict | None = None,
    riscrivi=_identita,
) -> aiohttp.ClientResponse:
    """GET following the redirects by hand instead of allow_redirects=True.

    Needed because the /services/oauth2/authorize redirect chain goes through a
    'startURL' parameter that contains a percent-encoded nested URL. Letting
    aiohttp handle the redirects itself, the behaviour depends on how the library
    re-encodes an already-encoded URL at each hop and can enter an infinite loop
    (TooManyRedirects). Following the redirects explicitly with encoded=True on
    the next hop's URL, the Location value is never re-processed: the same chain
    that loops with allow_redirects=True resolves here in a few hops.

    'riscrivi' rewrites each hop's URL onto the active host (see
    AuthClient._su_host): a Location can point to the custom domain behind
    Imperva, and following it as-is would land on the anti-bot page instead of
    the destination.

    Returns the final response (status < 300, no further Location); the caller is
    responsible for closing/consuming 'resp' as usual.
    """
    resp = await session.get(url, params=params, headers=headers, allow_redirects=False)

    for _ in range(_MAX_REDIRECT_HOPS):
        location = resp.headers.get("Location")
        if location is None:
            return resp

        resp.close()
        location_url = aiohttp.client.URL(location, encoded=True)
        next_url = location_url if location_url.is_absolute() else resp.url.join(location_url)
        next_url = aiohttp.client.URL(riscrivi(str(next_url)), encoded=True)
        resp = await session.get(next_url, headers=headers, allow_redirects=False)

    resp.close()
    raise AuthError(
        f"Troppi redirect (>{_MAX_REDIRECT_HOPS}) seguendo {url}: possibile "
        "cambiamento lato Salesforce nella struttura dei redirect di login."
    )


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _make_pkce_pair() -> tuple[str, str]:
    verifier = _b64url(secrets.token_bytes(32))
    challenge = _b64url(hashlib.sha256(verifier.encode("ascii")).digest())
    return verifier, challenge


@dataclass
class _LoginFlowState:
    """Everything needed to carry from the OTP page to its submission."""

    fwuid: str | None = None
    aura_token: str | None = None
    view_state: str | None = None
    view_state_version: str | None = None
    view_state_mac: str | None = None
    view_state_csrf: str | None = None
    form_action_url: str | None = None
    # The prefixes of the fields under 'thePage:j_id2:i:f:...' are generated by
    # Salesforce and vary between deploys: the name discovered on the real page
    # is kept instead of assuming the hardcoded ones (used only as a fallback in
    # the respective form builders).
    otp_field_name: str | None = None
    resend_field_name: str | None = None
    # The visible "Richiedi nuovo OTP" checkbox, twin of the hidden field above:
    # used only for an explicit resend, where we reproduce a browser's submit
    # with the box ticked.
    resend_checkbox_field_name: str | None = None
    next_field_name: str | None = None


@dataclass
class OAuthTokens:
    access_token: str
    refresh_token: str
    instance_url: str
